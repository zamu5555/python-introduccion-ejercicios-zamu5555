# ejercicio_07.py
# Título: Edad en Meses y Días Aproximados
#
# Descripción del Problema:
# Una aplicación de registro personal necesita mostrar la edad de una persona
# en diferentes unidades de tiempo. El programa debe calcular la edad en meses
# y en días aproximados a partir de la edad ingresada en años.
#
# Requisitos Específicos:
# 1. Solicitar el nombre del usuario.
# 2. Solicitar la edad en años.
# 3. Convertir la edad a tipo int.
# 4. Calcular la edad en meses.
# 5. Calcular la edad en días aproximados (1 año = 365 días).
# 6. Mostrar los resultados usando print() y f-strings.
#
# Ejemplo de Entrada:
# Nombre: Daniel
# Edad: 18
#
# Ejemplo de Salida Esperada:
# Daniel, tu edad en meses es: 216
# Daniel, tu edad en días aproximados es: 6570
