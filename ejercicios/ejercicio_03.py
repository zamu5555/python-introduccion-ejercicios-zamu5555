# ejercicio_03.py
# Título: ¿Cuántos años tendré?
#
# Descripción del Problema:
# Este programa debe ayudar a una persona a calcular cuántos años tendrá
# o tuvo, a partir de su edad actual y una cantidad de años que el usuario
# decida sumar o restar. Si el resultado es menor que cero, el programa
# debe mostrar un mensaje indicando que la persona aún no había nacido.
#
# Requisitos Específicos:
# 1. Solicitar al usuario su edad actual usando input().
# 2. Solicitar una cantidad de años a sumar o restar (puede ser positiva o negativa).
# 3. Convertir los valores ingresados a tipo int.
# 4. Calcular la nueva edad usando una operación aritmética.
# 5. Mostrar el resultado usando print() y f-strings.
# 6. Mantener una correcta indentación en todo el programa.
#
# Ejemplo de Entrada:
# Edad actual: 20
# Años a sumar o restar: 5
#
# Ejemplo de Salida Esperada:
# Dentro de 5 años tendrás 25 años.
#
# Ejemplo de Entrada:
# Edad actual: 20
# Años a sumar o restar: -25
#
# Ejemplo de Salida Esperada:
# En ese momento aún no habías nacido.
#
# Pista:
# Primero calcula la nueva edad y luego revisa si el resultado es menor que cero.
