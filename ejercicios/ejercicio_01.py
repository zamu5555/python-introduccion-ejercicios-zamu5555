# Título: Área de una Mesa Rectangular
#
# Descripción del Problema:
# Una persona quiere calcular el área de una mesa rectangular para saber
# cuánta superficie ocupa. El programa debe solicitar las medidas
# y mostrar el área total.
#
# Requisitos Específicos:
# 1. Solicitar el largo de la mesa.
# 2. Solicitar el ancho de la mesa.
# 3. Convertir ambos valores a float.
# 4. Calcular el área usando una multiplicación.
# 5. Mostrar el resultado usando f-strings.
#
# Ejemplo de Entrada:
# Largo: 2.5
# Ancho: 1.2
#
# Ejemplo de Salida Esperada:
# El área de la mesa es: 3.0
#
# Pista:
# El área se obtiene multiplicando largo por ancho.
